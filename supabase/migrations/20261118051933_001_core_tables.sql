create extension if not exists pg_trgm with schema extensions;
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to anon, authenticated, service_role;

create type public.user_role as enum ('admin','dt','visitor');
create type public.foot_side as enum ('right','left');
create type public.season_status as enum ('draft','regular','playoffs','closed');
create type public.data_quality as enum ('verified','imported','partial','missing');
create type public.acquisition_kind as enum ('initial','signing','purchase','loan','swap','release_clause','admin');
create type public.lineup_status as enum ('draft','submitted');

create table public.positions (
  id smallint primary key check (id between 0 and 12),
  code text not null unique,
  name text not null,
  line text not null check (line in ('gk','def','mid','fwd'))
);

create table public.countries (
  id smallint primary key,
  name text,
  iso_code text
);

create table public.clubs (
  id integer generated by default as identity (start with 100) primary key,
  name text not null unique check (length(trim(name)) between 2 and 60),
  short_name text check (length(short_name) <= 5),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  crest_path text,
  primary_color text check (primary_color ~ '^#[0-9a-fA-F]{6}$'),
  secondary_color text check (secondary_color ~ '^#[0-9a-fA-F]{6}$'),
  founded_year smallint check (founded_year between 1800 and 2100),
  stadium text check (length(stadium) <= 80),
  nickname text check (length(nickname) <= 60),
  history text check (length(history) <= 6000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.club_kits (
  club_id integer not null references public.clubs(id) on delete cascade,
  kind text not null check (kind in ('home','away','third')),
  image_path text not null,
  updated_at timestamptz not null default now(),
  primary key (club_id, kind)
);

create table public.rivalries (
  id integer generated always as identity primary key,
  club_a integer not null references public.clubs(id),
  club_b integer not null references public.clubs(id),
  name text not null check (length(name) <= 60),
  check (club_a <> club_b)
);
create unique index rivalries_pair_key on public.rivalries (least(club_a, club_b), greatest(club_a, club_b));
create index rivalries_club_b_idx on public.rivalries (club_b);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text check (length(display_name) <= 80),
  avatar_url text,
  role public.user_role not null default 'visitor',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.coaches (
  id integer generated always as identity primary key,
  name text not null check (length(trim(name)) between 2 and 80),
  profile_id uuid unique references public.profiles(id) on delete set null,
  avatar_url text,
  data_quality public.data_quality not null default 'imported',
  created_at timestamptz not null default now()
);

create table public.seasons (
  id integer generated always as identity primary key,
  number integer not null unique check (number > 0),
  name text,
  status public.season_status not null default 'draft',
  is_current boolean not null default false,
  data_quality public.data_quality not null default 'verified',
  started_at timestamptz,
  closed_at timestamptz,
  notes text,
  created_at timestamptz not null default now()
);
create unique index seasons_one_current on public.seasons (is_current) where is_current;

create table public.coach_tenures (
  id integer generated always as identity primary key,
  coach_id integer not null references public.coaches(id) on delete cascade,
  club_id integer not null references public.clubs(id),
  from_season integer references public.seasons(id),
  to_season integer references public.seasons(id),
  is_current boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index coach_tenures_current_coach on public.coach_tenures (coach_id) where is_current;
create unique index coach_tenures_current_club on public.coach_tenures (club_id) where is_current;
create index coach_tenures_coach_idx on public.coach_tenures (coach_id);
create index coach_tenures_club_idx on public.coach_tenures (club_id);
create index coach_tenures_from_idx on public.coach_tenures (from_season);
create index coach_tenures_to_idx on public.coach_tenures (to_season);

create table public.season_rules (
  season_id integer primary key references public.seasons(id) on delete cascade,
  squad_size smallint not null default 18 check (squad_size between 11 and 40),
  starters smallint not null default 11 check (starters = 11),
  bench smallint not null default 7 check (bench >= 0),
  budget numeric(10,1) not null default 150 check (budget >= 0),
  enforce_balance boolean not null default true,
  star_rating smallint not null default 81 check (star_rating between 50 and 99),
  required_stars smallint not null default 1 check (required_stars >= 0),
  clause_premium_pct numeric(5,2) not null default 40 check (clause_premium_pct >= 0),
  release_discount_pct numeric(5,2) not null default 20 check (release_discount_pct between 0 and 100),
  points_win smallint not null default 3,
  points_draw smallint not null default 1,
  points_loss smallint not null default 0,
  rounds smallint not null default 1 check (rounds in (1,2)),
  tiebreakers text[] not null default array['points','goal_diff','goals_for'],
  playoff_spots smallint not null default 6 check (playoff_spots = 6),
  relegation_spots smallint not null default 4 check (relegation_spots = 4),
  league_prizes numeric(10,1)[] not null default array[24,21.6,19.2,16.8,14.4,12,9.6,7.2,4.8,2.4]::numeric(10,1)[],
  playoff_prizes numeric(10,1)[] not null default array[16,12.8,9.6,6.4,0]::numeric(10,1)[],
  check (tiebreakers <@ array['points','goal_diff','goals_for','goals_against','wins','head_to_head'])
);

create table public.price_scales (
  season_id integer not null references public.seasons(id) on delete cascade,
  overall smallint not null check (overall between 1 and 99),
  value numeric(10,1) not null check (value >= 0),
  primary key (season_id, overall)
);

create table public.season_clubs (
  season_id integer not null references public.seasons(id) on delete cascade,
  club_id integer not null references public.clubs(id),
  is_active boolean not null default true,
  tiebreak_rank smallint,
  primary key (season_id, club_id)
);
create index season_clubs_club_idx on public.season_clubs (club_id);

create table public.legacy_title_totals (
  club_id integer primary key references public.clubs(id),
  titles smallint not null check (titles >= 0),
  through_season integer not null,
  note text
);

create sequence public.players_id_seq start with 1000000 minvalue 1;
create table public.players (
  id integer primary key default nextval('public.players_id_seq'),
  name text not null check (length(trim(name)) > 0),
  search_name text not null,
  country_id smallint references public.countries(id),
  age smallint check (age between 10 and 70),
  height_cm smallint,
  weight_kg smallint,
  foot public.foot_side,
  main_position smallint not null references public.positions(id),
  secondary_positions smallint[] not null default '{}',
  position_ratings smallint[],
  overall smallint not null check (overall between 1 and 99),
  attributes smallint[],
  photo_path text,
  market_value_override numeric(10,1) check (market_value_override >= 0),
  is_hidden boolean not null default false,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter sequence public.players_id_seq owned by public.players.id;
create index players_overall_idx on public.players (overall desc, id);
create index players_country_idx on public.players (country_id);
create index players_position_idx on public.players (main_position);
create index players_age_idx on public.players (age);
create index players_secondary_idx on public.players using gin (secondary_positions);
create index players_search_idx on public.players using gin (search_name extensions.gin_trgm_ops);

create table public.squad_memberships (
  id bigint generated always as identity primary key,
  club_id integer not null references public.clubs(id),
  player_id integer not null references public.players(id),
  acquisition public.acquisition_kind not null default 'initial',
  joined_at timestamptz not null default now(),
  left_at timestamptz,
  check (left_at is null or left_at >= joined_at)
);
create unique index squad_one_active_club on public.squad_memberships (player_id) where left_at is null;
create index squad_club_active_idx on public.squad_memberships (club_id) where left_at is null;
create index squad_player_idx on public.squad_memberships (player_id);

create table public.lineups (
  id integer generated always as identity primary key,
  club_id integer not null references public.clubs(id),
  season_id integer not null references public.seasons(id),
  formation text not null default '4-3-3' check (formation ~ '^[1-6](-[1-6]){1,3}$'),
  status public.lineup_status not null default 'draft',
  updated_at timestamptz not null default now(),
  unique (club_id, season_id)
);
create index lineups_season_idx on public.lineups (season_id);

create table public.lineup_slots (
  lineup_id integer not null references public.lineups(id) on delete cascade,
  slot smallint not null check (slot between 0 and 39),
  player_id integer references public.players(id),
  position_id smallint references public.positions(id),
  x numeric(5,2) check (x between 0 and 100),
  y numeric(5,2) check (y between 0 and 100),
  primary key (lineup_id, slot)
);
create unique index lineup_slots_unique_player on public.lineup_slots (lineup_id, player_id) where player_id is not null;
create index lineup_slots_player_idx on public.lineup_slots (player_id);
create index lineup_slots_position_idx on public.lineup_slots (position_id);

