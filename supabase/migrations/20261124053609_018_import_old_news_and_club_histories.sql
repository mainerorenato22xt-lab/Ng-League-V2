declare t record; v_player text; v_from text; v_to text; v_amount text; v_title text; v_body text; v_club integer;
begin
  for t in select * from public.transfers where kind in ('purchase', 'free_signing', 'club_release') order by id loop
    select name into v_player from public.players where id = t.player_id;
    select name into v_from from public.clubs where id = t.from_club;
    select name into v_to from public.clubs where id = t.to_club;
    v_amount := replace(regexp_replace(to_char(t.amount, 'FM999990.0'), '\.0$', ''), '.', ',') || ' M';
    if t.kind = 'purchase' then
      v_club := t.to_club; v_title := v_to || ' compró a ' || v_player; v_body := v_to || ' compró a ' || v_player || ' a ' || v_from || ' por ' || v_amount || '.';
    elsif t.kind = 'free_signing' then
      v_club := t.to_club; v_title := v_to || ' fichó a ' || v_player; v_body := v_to || ' fichó a ' || v_player || ', que estaba libre' || case when t.amount > 0 then ', por ' || v_amount else '' end || '.';
    else
      v_club := t.from_club; v_title := v_from || ' dejó libre a ' || v_player; v_body := v_from || ' dejó libre a ' || v_player || case when t.amount > 0 then ' y recibió ' || v_amount else '' end || '.';
    end if;
    insert into public.news_posts (auto_key, club_id, category, title, body, link_path, author_name, status, published_at)
    values ('transfer:' || t.id, v_club, 'transfer', v_title, v_body, '/jugadores/' || t.player_id, 'NG League', 'published', t.occurred_at)
    on conflict (auto_key) do nothing;
  end loop;
end $$;
